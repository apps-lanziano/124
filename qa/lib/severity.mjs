export const SEV_ORDER = { high:0, med:1, low:2, info:3 };
export const SEV_HE = { high:"🔴 חמור", med:"🟠 בינוני", low:"🟡 קל", info:"🔵 מידע" };

export function sortBySeverity(findings){
  return findings.slice().sort((a,b)=>SEV_ORDER[a.sev]-SEV_ORDER[b.sev]);
}
